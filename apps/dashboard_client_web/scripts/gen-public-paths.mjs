#!/usr/bin/env node
/* global process */
// Writes utils/publicPaths.generated.ts from the files under public/. The proxy matcher covers favicon/ too
// (a missing favicon file must 404). proxy.ts uses the list to let real
// dotted files through and 404 every other dotted path (cc.design.md section 18,
// candidate A2). `--check` compares without writing; exit 1 when stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = join(root, 'public');
const out = join(root, 'utils/publicPaths.generated.ts');

function list(dir, prefix) {
    return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
        e.isDirectory()
            ? list(join(dir, e.name), `${prefix}/${e.name}`)
            : [`${prefix}/${e.name}`]
    );
}

const paths = list(publicDir, '').sort();
const body = `// GENERATED by scripts/gen-public-paths.mjs from public/. Do not edit.
export const PUBLIC_PATHS: readonly string[] = [
${paths.map((x) => `    '${x}',`).join('\n')}
];
`;

if (process.argv.includes('--check')) {
    let current = '';
    try {
        current = readFileSync(out, 'utf8');
    } catch {
        // No generated file yet: treat as stale.
    }
    if (current !== body) {
        console.error(
            'publicPaths.generated.ts is stale: run node scripts/gen-public-paths.mjs'
        );
        process.exit(1);
    }
    console.log(`OK: PUBLIC_PATHS matches public/ (${paths.length} files)`);
} else {
    writeFileSync(out, body);
    console.log(`wrote ${paths.length} paths`);
}
